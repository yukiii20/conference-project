#!/bin/sh
# Rebuilds RUN-ALL-batch-3.sql from the individual batch-3 files.
cd "$(dirname "$0")"
FILES="04_agenda.sql 04_session_timing.sql 04_abstract_books.sql 04_feedback.sql"
OUT=RUN-ALL-batch-3.sql
{
  echo "-- ====================================================================="
  echo "-- MASTER FILE - features batch 3 (all SQL in one go)"
  echo "-- Generated by build-master.sh from: $FILES"
  echo "-- Run this ONE file in MySQL Workbench (File > Open SQL Script >"
  echo "-- lightning icon). Part 1 updates conference_cms, part 2 updates"
  echo "-- conference_cms_test. Every statement is safe to run more than once."
  echo "--"
  echo "-- On the live Aiven server there is no conference_cms_test: part 1"
  echo "-- finishes, then Workbench stops at part 2 with 'Unknown database"
  echo "-- conference_cms_test'. That error is expected and harmless there."
  echo "-- ====================================================================="
  echo "SET NAMES utf8mb4;"
  echo "SET time_zone = '+00:00';"
  echo
  echo "-- ===================== PART 1: conference_cms ====================="
  for f in $FILES; do echo; echo "-- ---------- $f ----------"; cat "$f"; done
  echo
  echo "-- ===================== PART 2: conference_cms_test ================"
  for f in $FILES; do echo; echo "-- ---------- $f (test database) ----------"; sed 's/\bconference_cms\b/conference_cms_test/g' "$f"; done
} > "$OUT"
echo "wrote $OUT"
