-- =====================================================================
-- Conference Management System - MySQL 8.0 schema
-- File: database/01_schema.sql
-- Run order: 01_schema.sql -> 02_reference_data.sql -> 03_triggers.sql
-- =====================================================================
-- Conventions
--  * MySQL 8.0.16 or newer (CHECK constraints, expression defaults).
--  * Primary keys: CHAR(36) UUIDs generated by the database (UUID()).
--    Append-only logs use BIGINT AUTO_INCREMENT.
--  * All DATETIME columns are stored in UTC. The backend must set
--    time_zone = '+00:00' on every connection and convert to
--    Asia/Kathmandu only when displaying.
--  * Text uses utf8mb4 with utf8mb4_0900_ai_ci, which is case-insensitive,
--    so 'A@B.COM' and 'a@b.com' count as the same email.
--  * Lists (keywords, file types, audiences, equipment) are JSON arrays.
--  * Conferences, submissions and users are never hard-deleted (soft
--    delete / status), so most foreign keys use RESTRICT.
--  * MySQL has no row-level security and no partial indexes:
--      - WHO may read or change a row is enforced by the Node backend.
--      - "Only one active X" rules use a generated flag column that is
--        1 when the rule applies and NULL otherwise; MySQL allows many
--        NULLs in a UNIQUE index, so only one active row can exist.
-- =====================================================================

SET NAMES utf8mb4;
SET time_zone = '+00:00';

CREATE DATABASE IF NOT EXISTS conference_cms_test
  CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE conference_cms_test;

-- =====================================================================
-- A. IDENTITY, AUTHENTICATION AND ACCESS
-- =====================================================================

CREATE TABLE users (
  id                  CHAR(36)     NOT NULL DEFAULT (UUID()),
  email               VARCHAR(254) NOT NULL,
  password_hash       VARCHAR(255) NULL,      -- bcrypt; NULL until an invited user sets a password
  email_verified_at   DATETIME(3)  NULL,
  full_name           VARCHAR(200) NOT NULL,
  phone               VARCHAR(16)  NULL,      -- E.164, e.g. +9779812345678
  institution         VARCHAR(300) NULL,
  department          VARCHAR(300) NULL,
  position            VARCHAR(200) NULL,
  bio                 TEXT         NULL,
  country             CHAR(2)      NULL,
  orcid               VARCHAR(19)  NULL,
  photo_path          VARCHAR(500) NULL,
  status              ENUM('active','suspended','deactivated') NOT NULL DEFAULT 'active',
  failed_login_count  SMALLINT     NOT NULL DEFAULT 0,
  locked_until        DATETIME(3)  NULL,
  last_login_at       DATETIME(3)  NULL,
  created_at          DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at          DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY users_email_uq (email),
  UNIQUE KEY users_orcid_uq (orcid),
  CONSTRAINT users_email_chk   CHECK (REGEXP_LIKE(email, '^[^@[:space:]]+@[^@[:space:]]+\\.[^@[:space:]]+$')),
  CONSTRAINT users_name_chk    CHECK (CHAR_LENGTH(TRIM(full_name)) BETWEEN 1 AND 200),
  CONSTRAINT users_phone_chk   CHECK (phone IS NULL OR REGEXP_LIKE(phone, '^\\+[1-9][0-9]{7,14}$')),
  CONSTRAINT users_country_chk CHECK (country IS NULL OR REGEXP_LIKE(country, '^[A-Z]{2}$', 'c')),
  CONSTRAINT users_orcid_chk   CHECK (orcid IS NULL OR REGEXP_LIKE(orcid, '^[0-9]{4}-[0-9]{4}-[0-9]{4}-[0-9]{3}[0-9X]$'))
) ENGINE=InnoDB COMMENT='Accounts and profiles (replaces Supabase auth.users + profiles)';

-- Login sessions. The cookie holds a random token; only its SHA-256 is stored.
CREATE TABLE auth_sessions (
  id            CHAR(36)    NOT NULL DEFAULT (UUID()),
  user_id       CHAR(36)    NOT NULL,
  token_hash    CHAR(64)    NOT NULL,
  remember_me   BOOLEAN     NOT NULL DEFAULT FALSE,
  is_admin_session BOOLEAN  NOT NULL DEFAULT FALSE,
  user_agent    VARCHAR(500) NULL,
  ip_address    VARCHAR(45) NULL,
  last_seen_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  expires_at    DATETIME(3) NOT NULL,
  revoked_at    DATETIME(3) NULL,
  created_at    DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY auth_sessions_token_uq (token_hash),
  KEY auth_sessions_user_idx (user_id, revoked_at),
  CONSTRAINT auth_sessions_user_fk FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- One-time links: password reset, email verification, convenor invitation.
CREATE TABLE auth_tokens (
  id           CHAR(36)    NOT NULL DEFAULT (UUID()),
  user_id      CHAR(36)    NOT NULL,
  purpose      ENUM('password_reset','email_verification','invitation') NOT NULL,
  token_hash   CHAR(64)    NOT NULL,
  expires_at   DATETIME(3) NOT NULL,
  used_at      DATETIME(3) NULL,
  created_by   CHAR(36)    NULL,
  created_at   DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY auth_tokens_token_uq (token_hash),
  KEY auth_tokens_user_idx (user_id, purpose),
  CONSTRAINT auth_tokens_user_fk    FOREIGN KEY (user_id)    REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT auth_tokens_creator_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE roles (
  code         VARCHAR(40)  NOT NULL,
  name         VARCHAR(100) NOT NULL,
  scope        ENUM('platform','conference','derived') NOT NULL,
  description  VARCHAR(500) NULL,
  created_at   DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (code),
  CONSTRAINT roles_code_chk CHECK (REGEXP_LIKE(code, '^[a-z_]{2,40}$', 'c'))
) ENGINE=InnoDB;

CREATE TABLE permissions (
  code         VARCHAR(60)  NOT NULL,
  module       VARCHAR(40)  NOT NULL,
  description  VARCHAR(500) NULL,
  created_at   DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (code),
  CONSTRAINT permissions_code_chk CHECK (REGEXP_LIKE(code, '^[a-z_]+\\.[a-z_]+$', 'c'))
) ENGINE=InnoDB;

CREATE TABLE role_permissions (
  role_code        VARCHAR(40) NOT NULL,
  permission_code  VARCHAR(60) NOT NULL,
  created_at       DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (role_code, permission_code),
  KEY role_permissions_perm_idx (permission_code),
  CONSTRAINT role_permissions_role_fk FOREIGN KEY (role_code)       REFERENCES roles (code)       ON DELETE CASCADE,
  CONSTRAINT role_permissions_perm_fk FOREIGN KEY (permission_code) REFERENCES permissions (code) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE platform_user_roles (
  user_id     CHAR(36)    NOT NULL,
  role_code   VARCHAR(40) NOT NULL,
  granted_by  CHAR(36)    NULL,
  granted_at  DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  PRIMARY KEY (user_id, role_code),
  KEY platform_user_roles_role_idx (role_code),
  CONSTRAINT platform_user_roles_user_fk    FOREIGN KEY (user_id)    REFERENCES users (id) ON DELETE CASCADE,
  CONSTRAINT platform_user_roles_role_fk    FOREIGN KEY (role_code)  REFERENCES roles (code),
  CONSTRAINT platform_user_roles_granter_fk FOREIGN KEY (granted_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB;

