CREATE TABLE conferences (
  id                     CHAR(36)     NOT NULL DEFAULT (UUID()),
  slug                   VARCHAR(80)  NOT NULL,
  code                   VARCHAR(20)  NOT NULL,
  name                   VARCHAR(300) NOT NULL,
  short_name             VARCHAR(50)  NULL,
  tagline                VARCHAR(200) NULL,
  theme                  VARCHAR(300) NULL,
  description            TEXT         NULL,
  welcome_text           TEXT         NULL,
  submission_guidelines  TEXT         NULL,
  logo_path              VARCHAR(500) NULL,
  banner_path            VARCHAR(500) NULL,
  primary_color          CHAR(7)      NULL,
  venue_name             VARCHAR(300) NULL,
  address                VARCHAR(500) NULL,
  city                   VARCHAR(100) NULL,
  country                CHAR(2)      NULL,
  location_map_url       VARCHAR(1000) NULL,
  timezone               VARCHAR(64)  NOT NULL DEFAULT 'Asia/Kathmandu',
  start_date             DATE         NOT NULL,
  end_date               DATE         NOT NULL,
  contact_email          VARCHAR(254) NULL,
  contact_phone          VARCHAR(16)  NULL,
  website_url            VARCHAR(500) NULL,
  social_links           JSON         NULL,
  status                 ENUM('draft','registration_open','submission_open','under_review',
                              'scheduling','published','ongoing','completed','closed')
                         NOT NULL DEFAULT 'draft',
  published_at           DATETIME(3)  NULL,
  created_by             CHAR(36)     NULL,
  deleted_at             DATETIME(3)  NULL,
  created_at             DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at             DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY conferences_slug_uq (slug),
  UNIQUE KEY conferences_code_uq (code),
  KEY conferences_status_idx (status, deleted_at),
  CONSTRAINT conferences_created_by_fk FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT conferences_slug_chk    CHECK (REGEXP_LIKE(slug, '^[a-z0-9]+(-[a-z0-9]+)*$', 'c')),
  CONSTRAINT conferences_code_chk    CHECK (REGEXP_LIKE(code, '^[A-Z0-9]{2,20}$', 'c')),
  CONSTRAINT conferences_name_chk    CHECK (CHAR_LENGTH(TRIM(name)) BETWEEN 3 AND 300),
  CONSTRAINT conferences_dates_chk   CHECK (end_date >= start_date),
  CONSTRAINT conferences_color_chk   CHECK (primary_color IS NULL OR REGEXP_LIKE(primary_color, '^#[0-9A-Fa-f]{6}$')),
  CONSTRAINT conferences_country_chk CHECK (country IS NULL OR REGEXP_LIKE(country, '^[A-Z]{2}$', 'c')),
  CONSTRAINT conferences_web_chk     CHECK (website_url IS NULL OR REGEXP_LIKE(website_url, '^https?://')),
  CONSTRAINT conferences_map_chk     CHECK (location_map_url IS NULL OR REGEXP_LIKE(location_map_url, '^https://')),
  CONSTRAINT conferences_texts_chk   CHECK ((welcome_text IS NULL OR CHAR_LENGTH(welcome_text) <= 3000)
                                        AND (submission_guidelines IS NULL OR CHAR_LENGTH(submission_guidelines) <= 10000))
) ENGINE=InnoDB;

CREATE TABLE conference_settings (
  conference_id                  CHAR(36)  NOT NULL,
  review_mode                    ENUM('open','single_blind','double_blind') NOT NULL DEFAULT 'double_blind',
  reviews_required               SMALLINT  NOT NULL DEFAULT 3,
  max_submissions_per_author     SMALLINT  NULL,
  max_abstract_words             SMALLINT  NOT NULL DEFAULT 300,
  max_file_size_mb               SMALLINT  NOT NULL DEFAULT 20,
  allowed_file_types             JSON      NOT NULL DEFAULT (JSON_ARRAY('pdf','doc','docx')),
  registration_requires_payment  BOOLEAN   NOT NULL DEFAULT TRUE,
  registration_capacity          INT       NULL,
  session_attendance_enabled     BOOLEAN   NOT NULL DEFAULT FALSE,
  certificate_min_sessions       SMALLINT  NULL,
  authors_see_review_comments    BOOLEAN   NOT NULL DEFAULT TRUE,
  default_currency               CHAR(3)   NOT NULL DEFAULT 'NPR',
  created_at                     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at                     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (conference_id),
  CONSTRAINT conference_settings_conf_fk FOREIGN KEY (conference_id) REFERENCES conferences (id),
  CONSTRAINT conference_settings_reviews_chk  CHECK (reviews_required BETWEEN 1 AND 10),
  CONSTRAINT conference_settings_maxsub_chk   CHECK (max_submissions_per_author IS NULL OR max_submissions_per_author > 0),
  CONSTRAINT conference_settings_words_chk    CHECK (max_abstract_words BETWEEN 50 AND 2000),
  CONSTRAINT conference_settings_size_chk     CHECK (max_file_size_mb BETWEEN 1 AND 100),
  CONSTRAINT conference_settings_cap_chk      CHECK (registration_capacity IS NULL OR registration_capacity > 0),
  CONSTRAINT conference_settings_types_chk    CHECK (JSON_TYPE(allowed_file_types) = 'ARRAY'),
  CONSTRAINT conference_settings_currency_chk CHECK (REGEXP_LIKE(default_currency, '^[A-Z]{3}$', 'c'))
) ENGINE=InnoDB;

CREATE TABLE conference_members (
  id               CHAR(36)    NOT NULL DEFAULT (UUID()),
  conference_id    CHAR(36)    NOT NULL,
  user_id          CHAR(36)    NOT NULL,
  role_code        VARCHAR(40) NOT NULL,
  title            VARCHAR(200) NULL,
  status           ENUM('active','removed') NOT NULL DEFAULT 'active',
  is_public        BOOLEAN     NOT NULL DEFAULT FALSE,
  max_review_load  SMALLINT    NULL,
  added_by         CHAR(36)    NULL,
  -- 1 only for the active convenor row; enforces ONE active convenor per conference
  active_convenor_flag TINYINT GENERATED ALWAYS AS
    (IF(role_code = 'convenor' AND status = 'active', 1, NULL)) STORED,
  created_at       DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at       DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY conference_members_role_uq (conference_id, user_id, role_code),
  UNIQUE KEY conference_members_one_convenor_uq (conference_id, active_convenor_flag),
  KEY conference_members_user_idx (user_id, status),
  KEY conference_members_conf_role_idx (conference_id, role_code, status),
  CONSTRAINT conference_members_conf_fk  FOREIGN KEY (conference_id) REFERENCES conferences (id),
  CONSTRAINT conference_members_user_fk  FOREIGN KEY (user_id)       REFERENCES users (id),
  CONSTRAINT conference_members_role_fk  FOREIGN KEY (role_code)     REFERENCES roles (code),
  CONSTRAINT conference_members_added_fk FOREIGN KEY (added_by)      REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT conference_members_load_chk CHECK (max_review_load IS NULL OR max_review_load > 0)
) ENGINE=InnoDB;

-- Sign-up role requests approved or rejected by the convenor.
CREATE TABLE role_requests (
  id             CHAR(36)    NOT NULL DEFAULT (UUID()),
  user_id        CHAR(36)    NOT NULL,
  conference_id  CHAR(36)    NOT NULL,
  role_code      ENUM('author','reviewer','session_chair','staff','manager') NOT NULL,
  status         ENUM('pending','approved','rejected','cancelled') NOT NULL DEFAULT 'pending',
  note           VARCHAR(500) NULL,
  reject_reason  VARCHAR(500) NULL,
  reviewed_by    CHAR(36)    NULL,
  reviewed_at    DATETIME(3) NULL,
  pending_flag   TINYINT GENERATED ALWAYS AS (IF(status = 'pending', 1, NULL)) STORED,
  created_at     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at     DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  PRIMARY KEY (id),
  UNIQUE KEY role_requests_one_pending_uq (user_id, conference_id, role_code, pending_flag),
  KEY role_requests_conf_status_idx (conference_id, status),
  CONSTRAINT role_requests_user_fk     FOREIGN KEY (user_id)       REFERENCES users (id),
  CONSTRAINT role_requests_conf_fk     FOREIGN KEY (conference_id) REFERENCES conferences (id),
  CONSTRAINT role_requests_reviewer_fk FOREIGN KEY (reviewed_by)   REFERENCES users (id) ON DELETE SET NULL,
  CONSTRAINT role_requests_reason_chk  CHECK (status <> 'rejected' OR reject_reason IS NOT NULL)
) ENGINE=InnoDB;

